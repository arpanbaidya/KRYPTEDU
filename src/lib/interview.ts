export const RUBRIC = {
  Technical: ["Technical correctness", "Relevance and completeness", "Problem-solving explanation"],
  "HR/Behavioral": [
    "Clarity and structure",
    "Relevance to the question",
    "Specificity and concrete examples",
  ],
} as const;

/** Criteria weights for detailed technical evaluations. */
export const CRITERIA_WEIGHTS: Record<string, number> = {
  "Technical correctness": 0.4,
  "Relevance and completeness": 0.3,
  "Problem-solving explanation": 0.3,
  "Clarity and structure": 0.35,
  "Relevance to the question": 0.35,
  "Specificity and concrete examples": 0.3,
};

const str = (v: unknown, max = 2000) => (typeof v === "string" ? v.trim().slice(0, max) : "");

const strs = (v: unknown) =>
  Array.isArray(v)
    ? v
        .map((x) => str(x, 500))
        .filter(Boolean)
        .slice(0, 6)
    : [];

const pct = (v: unknown) => {
  const n = Math.round(Number(v));
  return Number.isFinite(n) ? Math.max(0, Math.min(100, n)) : null;
};

/**
 * Validates and deduplicates questions generated by Gemini.
 * Discards questions that are duplicates or too short.
 */
export function validateQuestions(raw: unknown, count: number, type: string): Question[] | null {
  const list = (raw as { questions?: unknown })?.questions;
  if (!Array.isArray(list)) return null;

  const seenTexts = new Set<string>();

  const qs: Question[] = [];
  for (const q of list as any[]) {
    const text = str(q?.text || q?.prompt || q?.question, 600);
    const normalized = text.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (text.length <= 15 || seenTexts.has(normalized)) continue;
    seenTexts.add(normalized);

    const rawKind = q?.kind || q?.type;
    const kind: Question["kind"] =
      type === "Mixed"
        ? (rawKind === "HR/Behavioral" || String(rawKind).toLowerCase().includes("hr") || String(rawKind).toLowerCase().includes("behavioral"))
          ? "HR/Behavioral"
          : "Technical"
        : (type as Question["kind"]);

    qs.push({
      text,
      kind,
      topic: str(q?.topic, 80) || "General",
    });
  }

  return qs.length >= count ? qs.slice(0, count) : null;
}

/**
 * Validates the AI evaluation against the configured rubric.
 * The overall score is calculated as the mean of criteria scores
 * ensuring strict consistency between criteria and total.
 */
export function validateEvaluation(raw: unknown, kind: Question["kind"]): Evaluation | null {
  const r = raw as any;
  const names = RUBRIC[kind];
  const criteria: Criterion[] = [];

  for (const name of names) {
    const hit = Array.isArray(r?.criteria)
      ? r.criteria.find((c: any) => str(c?.name).toLowerCase() === name.toLowerCase())
      : null;
    const s = pct(hit?.score);
    if (s === null) return null;
    criteria.push({ name, score: s });
  }

  const feedback = str(r?.feedback);
  if (!feedback) return null;

  const score = Math.round(criteria.reduce((a, c) => a + c.score, 0) / criteria.length);

  return {
    score,
    criteria,
    feedback,
    strengths: strs(r?.strengths),
    improvements: strs(r?.improvements),
    better_answer: str(r?.better_answer, 3000),
  };
}

export function validateSummary(raw: unknown): Summary | null {
  const r = raw as any;
  const overview = str(r?.overview);
  if (!overview) return null;
  return {
    overview,
    overall_score: pct(r?.overall_score) ?? undefined,
    technical_score: pct(r?.technical_score) ?? undefined,
    communication_score: pct(r?.communication_score) ?? undefined,
    problem_solving_score: pct(r?.problem_solving_score) ?? undefined,
    strongest_areas: strs(r?.strongest_areas),
    weakest_areas: strs(r?.weakest_areas),
    recurring_weaknesses: strs(r?.recurring_weaknesses),
    topics_to_practise: strs(r?.topics_to_practise),
    suggested_practice_questions: strs(r?.suggested_practice_questions),
    preparation_plan: strs(r?.preparation_plan),
    next_steps: strs(r?.next_steps),
  };
}

export function overallScore(answers: Answer[]) {
  return answers.length
    ? Math.round(answers.reduce((a, x) => a + x.evaluation.score, 0) / answers.length)
    : 0;
}

