/**
 * Returns a fallback set of questions tailored to the specified parameters.
 */
export function getFallbackQuestions(
  role: string,
  level: string,
  type: string,
  count: number,
): Question[] {
  const roleBank = QUESTION_BANK[role] ?? QUESTION_BANK["General Technical"]!;
  const levelBank = roleBank[level] ?? roleBank["Intermediate"]!;

  let filtered = levelBank;
  if (type === "Technical") {
    filtered = levelBank.filter((q) => q.kind === "Technical");
  } else if (type === "HR/Behavioral") {
    filtered = levelBank.filter((q) => q.kind === "HR/Behavioral");
  }

  // If filtered pool is smaller than required, supplement from other levels of the same role
  if (filtered.length < count) {
    const allRoleQuestions = Object.values(roleBank).flat();
    const additional = allRoleQuestions.filter(
      (q) => (type === "Mixed" || q.kind === type) && !filtered.some((x) => x.text === q.text),
    );
    filtered = [...filtered, ...additional];
  }

  return filtered.slice(0, count);
}

/**
 * Deterministic heuristic evaluation for offline/fallback mode.
 * Evaluates answer substance, keyword presence, structure, and length.
 */
export function evaluateAnswerDeterministically(
  question: Question,
  answerText: string,
  targetRole: string,
): Evaluation {
  const clean = answerText.trim();
  const words = clean.split(/\s+/).filter(Boolean);
  const wordCount = words.length;

  // 1. Trivial or empty answers
  if (wordCount < 5) {
    return {
      score: 15,
      criteria: RUBRIC[question.kind].map((name) => ({ name, score: 15 })),
      feedback:
        "The submitted answer is too brief to demonstrate technical competence or clear reasoning.",
      strengths: ["Submitted an initial response"],
      improvements: [
        "Elaborate on core concepts with clear explanations",
        "Provide concrete examples and technical terminology",
        "Structure answers clearly with beginning, explanation, and conclusion",
      ],
      better_answer: `For this question on "${question.topic}", a strong answer should define the concept clearly, explain the underlying mechanism, and give a practical example demonstrating real-world usage.`,
    };
  }

  // 2. Base scoring on depth, structure, and technical indicators
  let technicalScore = 65;
  let relevanceScore = 70;
  let reasoningScore = 65;

  if (wordCount >= 30) technicalScore += 10;
  if (wordCount >= 60) technicalScore += 10;
  if (wordCount >= 100) reasoningScore += 10;

  // Look for structural markers (e.g. because, for example, first, secondly, in contrast, tradeoff)
  const lower = clean.toLowerCase();
  const hasExample =
    lower.includes("example") ||
    lower.includes("for instance") ||
    lower.includes("such as") ||
    lower.includes("e.g.");
  const hasReasoning =
    lower.includes("because") ||
    lower.includes("therefore") ||
    lower.includes("trade-off") ||
    lower.includes("however");
  const hasCodeOrTechnical =
    lower.includes("function") ||
    lower.includes("class") ||
    lower.includes("database") ||
    lower.includes("algorithm") ||
    lower.includes("time complexity");

  if (hasExample) relevanceScore = Math.min(95, relevanceScore + 10);
  if (hasReasoning) reasoningScore = Math.min(95, reasoningScore + 10);
  if (hasCodeOrTechnical) technicalScore = Math.min(95, technicalScore + 10);

  technicalScore = Math.min(95, Math.max(30, technicalScore));
  relevanceScore = Math.min(95, Math.max(30, relevanceScore));
  reasoningScore = Math.min(95, Math.max(30, reasoningScore));

  const criteria: Criterion[] =
    question.kind === "Technical"
      ? [
          { name: "Technical correctness", score: technicalScore },
          { name: "Relevance and completeness", score: relevanceScore },
          { name: "Problem-solving explanation", score: reasoningScore },
        ]
      : [
          { name: "Clarity and structure", score: reasoningScore },
          { name: "Relevance to the question", score: relevanceScore },
          { name: "Specificity and concrete examples", score: hasExample ? 85 : 60 },
        ];

  const overall = Math.round(criteria.reduce((a, c) => a + c.score, 0) / criteria.length);

  return {
    score: overall,
    criteria,
    feedback: `Good effort addressing "${question.topic}". The answer shows reasonable comprehension. To score higher, deepen technical specificity and highlight architectural or practical trade-offs.`,
    strengths: [
      `Addressed the core topic of ${question.topic}`,
      wordCount >= 40 ? "Provided adequate explanation depth" : "Concise answer structure",
      hasReasoning ? "Included logical justification" : "Clear direct statements",
    ].slice(0, 2),
    improvements: [
      !hasExample
        ? "Include concrete real-world code or situational examples"
        : "Elaborate further on edge cases",
      "Mention computational efficiency, constraints, or trade-offs",
    ],
    better_answer: `A comprehensive answer for a ${targetRole} candidate: Start by defining ${question.topic} precisely. Next, walk through how it operates under typical constraints. Finally, discuss practical trade-offs (e.g. time vs space complexity, scalability) encountered in real systems.`,
  };
}
